"use client";

import { useState } from "react";
import { useRouter } from "next/navigation";
import { SecretReveal, SentryButton, StateView, StepFlow } from "@repo/ui";
import { useCopy } from "@/i18n";
import { authRoutes } from "@/constants/routes";
import { OTP_LENGTH, SECRET_AUTO_HIDE_MS } from "@/constants/limits";
import { useMfaEnroll } from "../api/use-mfa-enroll";
import type { PublicTenantBranding } from "../api/tenant-branding";
import { CodeField } from "../components/CodeField";
import { FormAlert } from "../components/FormAlert";
import { HostedFrame } from "../components/HostedFrame";
import { SuccessPanel } from "../components/SuccessPanel";
import { ENROLL_STEPS, formatRecoveryCode, manualKeyGroups } from "../model/enroll";
import { defaultDashboard } from "../model/outcome";

export function MfaEnrollView({ branding }: { branding?: PublicTenantBranding | null }) {
  const { t, tk } = useCopy();
  const router = useRouter();
  const flow = useMfaEnroll();
  const [code, setCode] = useState("");
  const toDashboard = (): void => router.replace(defaultDashboard(flow.tenantSlug));

  if (flow.session === "checking") {
    return (
      <HostedFrame title={t("auth.enroll.introTitle")} branding={branding}>
        <StateView kind="loading" title={t("auth.enroll.checking")} />
      </HostedFrame>
    );
  }

  if (flow.session === "signed-out") {
    return (
      <HostedFrame title={t("auth.enroll.signInRequiredTitle")} description={t("auth.enroll.signInRequiredDescription")} branding={branding}>
        <p className="mb-4 font-body text-xs text-muted-foreground">{t("auth.enroll.pendingContractNotice")}</p>
        <SentryButton type="button" variant="accent" className="w-full" onClick={() => router.push(authRoutes.login())}>
          {t("auth.mfa.restart")}
        </SentryButton>
      </HostedFrame>
    );
  }

  const steps = ENROLL_STEPS.map((id) => ({ id, label: tk(`auth.enroll.steps.${id}`) }));
  const index = ENROLL_STEPS.indexOf(flow.step);
  const titleKey = {
    intro: "auth.enroll.introTitle",
    setup: "auth.enroll.setupTitle",
    recovery: "auth.enroll.recoveryTitle",
    done: "auth.enroll.doneTitle",
  } as const;
  const descKey = {
    intro: "auth.enroll.introDescription",
    setup: "auth.enroll.setupDescription",
    recovery: "auth.enroll.recoveryDescription",
    done: "auth.enroll.doneDescription",
  } as const;

  const body = (() => {
    switch (flow.step) {
      case "intro":
        return (
          <SentryButton type="button" className="w-full" isLoading={flow.pending} onClick={() => void flow.start()}>
            {t("auth.enroll.start")}
          </SentryButton>
        );
      case "setup":
        return (
          <form
            className="space-y-4"
            onSubmit={(event) => {
              event.preventDefault();
              if (code.length === OTP_LENGTH) void flow.confirm(code);
            }}
          >
            {flow.setup && (
              <>
                {/* The QR is a data URL generated by our own API, so next/image adds nothing. */}
                {/* eslint-disable-next-line @next/next/no-img-element */}
                <img src={flow.setup.qrCode} alt={t("auth.enroll.qrAlt")} className="mx-auto h-44 w-44 rounded-sm bg-background p-2" />
                <details className="font-body text-sm text-muted-foreground">
                  <summary className="cursor-pointer text-foreground">{t("auth.enroll.manualKey")}</summary>
                  <p className="mt-2 break-all font-mono text-xs text-foreground">{manualKeyGroups(flow.setup.secret)}</p>
                </details>
              </>
            )}
            <CodeField
              label={t("auth.enroll.codeLabel")}
              value={code}
              onChange={setCode}
              onComplete={(value) => void flow.confirm(value)}
              error={flow.failure ? t("auth.enroll.invalidCode") : undefined}
              disabled={flow.pending}
              autoFocus
            />
            <SentryButton type="submit" className="w-full" isLoading={flow.pending} disabled={code.length < OTP_LENGTH}>
              {t("auth.enroll.confirm")}
            </SentryButton>
          </form>
        );
      case "recovery":
        return (
          <SecretReveal
            secret={flow.codes.map(formatRecoveryCode).join("  ")}
            fieldLabel={t("auth.enroll.recoveryField")}
            labels={{
              warning: t("auth.enroll.secretLabels.warning"),
              copy: t("auth.enroll.secretLabels.copy"),
              copied: t("auth.enroll.secretLabels.copied"),
              copyFailed: t("auth.enroll.secretLabels.copyFailed"),
              show: t("auth.enroll.secretLabels.show"),
              hide: t("auth.enroll.secretLabels.hide"),
              hiddenValue: t("auth.enroll.secretLabels.hiddenValue"),
              acknowledge: t("auth.enroll.secretLabels.acknowledge"),
            }}
            autoHideMs={SECRET_AUTO_HIDE_MS}
            onAcknowledge={flow.acknowledgeCodes}
          />
        );
      case "done":
        return (
          <SuccessPanel
            title={t("auth.enroll.doneTitle")}
            description={t("auth.enroll.doneDescription")}
            actionLabel={t("auth.enroll.finish")}
            onAction={toDashboard}
          />
        );
    }
  })();

  return (
    <HostedFrame title={tk(titleKey[flow.step])} description={tk(descKey[flow.step])} branding={branding}>
      <StepFlow
        steps={steps}
        currentId={flow.step}
        progressLabel={t("auth.steps.progress", { current: index + 1, total: ENROLL_STEPS.length })}
        stepLabel={(step, i) => t("auth.steps.stepLabel", { index: i + 1, label: step.label })}
      >
        {flow.step !== "setup" && <FormAlert message={flow.failure ? t("auth.login.failures.generic") : undefined} className="mb-4" />}
        {body}
      </StepFlow>
    </HostedFrame>
  );
}
